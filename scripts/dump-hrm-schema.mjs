#!/usr/bin/env node
// Write the git-side people schema (JSON + prose) from the live catalogs.
// Run after changing fields/invariants so the committed dump matches the code.
//   node scripts/dump-hrm-schema.mjs
//   node scripts/dump-hrm-schema.mjs --check   fail if dump is stale
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildCoreSchema, prettySchemaJson, renderSchemaText } from '../core/hrm-schema/build.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'docs', 'hrm-schema')
const jsonPath = join(dir, 'people.json')
const textPath = join(dir, 'people.md')
const checkOnly = process.argv.includes('--check')

const schema = buildCoreSchema()
const json = prettySchemaJson(schema)
const text = `# FranHRM people schema (git source)\n\nThis file is generated by \`npm run schema:dump\` from \`core/staff/fields.mjs\`, \`core/permissions/catalog.mjs\` and \`core/hrm-schema/invariants.mjs\`. Do not edit it by hand.\n\n\`\`\`\n${renderSchemaText(schema)}\n\`\`\`\n`

function read(path) {
  try { return readFileSync(path, 'utf8') } catch { return null }
}

if (checkOnly) {
  const jsonOk = read(jsonPath) === json
  const textOk = read(textPath) === text
  if (jsonOk && textOk) {
    console.log('hrm schema dump in sync')
    process.exit(0)
  }
  console.error('hrm schema dump is stale. Run: npm run schema:dump')
  if (!jsonOk) console.error('  drifted: docs/hrm-schema/people.json')
  if (!textOk) console.error('  drifted: docs/hrm-schema/people.md')
  process.exit(1)
}

mkdirSync(dir, { recursive: true })
writeFileSync(jsonPath, json)
writeFileSync(textPath, text)
console.log('wrote docs/hrm-schema/people.json')
console.log('wrote docs/hrm-schema/people.md')
